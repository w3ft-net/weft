package shapegen

import (
	"go/format"
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

const defaultYAML = "coordinates: [namespace, env, service, kind]\n"

// An odd shape: an extra base coordinate, and two added columns of both types.
const oddYAML = `
coordinates: [namespace, region, service]
added:
  - {name: account_id, type: int64, role: partition, pinned: true, required: true}
  - {name: tier, type: string, role: partition, pinned: true, required: true}
`

// squash collapses runs of whitespace so a check does not depend on how gofmt
// aligned a struct's fields.
func squash(s string) string { return strings.Join(strings.Fields(s), " ") }

func gen(t *testing.T, yaml string) string {
	t.Helper()
	s, err := ParseSpec([]byte(yaml))
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate(s, "test.yaml")
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	return string(out)
}

// Every shape generates Go that parses and is already gofmt-clean, so the
// committed output never churns.
func TestGenerate_IsValidFormattedGo(t *testing.T) {
	for name, y := range map[string]string{"hosted": hostedYAML, "default": defaultYAML, "odd": oddYAML} {
		t.Run(name, func(t *testing.T) {
			src := gen(t, y)
			if _, err := parser.ParseFile(token.NewFileSet(), "coord_gen.go", src, parser.AllErrors); err != nil {
				t.Fatalf("does not parse: %v\n%s", err, src)
			}
			formatted, err := format.Source([]byte(src))
			if err != nil || string(formatted) != src {
				t.Fatalf("not gofmt-stable (err %v)", err)
			}
			if !strings.HasPrefix(src, "// Code generated by shapegen from test.yaml; DO NOT EDIT.") {
				t.Errorf("missing the generated-code header:\n%s", src[:120])
			}
		})
	}
}

// The tuple has a field per column: a concrete value for a required one, a Cell
// for the rest; the key a row is matched by has a plain value for each.
func TestGenerate_HostedShape(t *testing.T) {
	src := squash(gen(t, hostedYAML))
	for _, want := range []string{
		"Customer int64",
		"Namespace Cell",
		"Env Cell",
		"Service Cell",
		"Kind Cell",
		"Namespace string",
		`LayoutColumn{Name: "customer_id", Type: TypeInt64, Role: RolePartition}`,
		"strconv.FormatInt(c.Customer, 10)",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated hosted shape lacks %q", want)
		}
	}
}

func TestGenerate_DefaultShapeHasNoTenantAnywhere(t *testing.T) {
	src := gen(t, defaultYAML)
	for _, banned := range []string{"Customer", "customer", "strconv"} {
		if strings.Contains(src, banned) {
			t.Errorf("the default shape's generated code mentions %q", banned)
		}
	}
	if !strings.Contains(src, "NewLayout()") {
		t.Errorf("the default layout has no partition columns:\n%s", src)
	}
}

func TestGenerate_OddShapeKeepsPartitionOrder(t *testing.T) {
	src := squash(gen(t, oddYAML))
	a, b := strings.Index(src, `Name: "account_id"`), strings.Index(src, `Name: "tier"`)
	if a < 0 || b < a {
		t.Errorf("layout columns are not in spec order (account_id at %d, tier at %d)", a, b)
	}
	for _, want := range []string{"AccountId int64", "Tier string", "Region Cell"} {
		if !strings.Contains(src, want) {
			t.Errorf("generated odd shape lacks %q", want)
		}
	}
}
