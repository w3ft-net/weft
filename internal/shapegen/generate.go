package shapegen

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"
)

// data is what the template is filled from.
type data struct {
	Source string
	// Cols are every column, in order. Required are the ones that are a
	// concrete value in a tuple, Cells the ones that are a Cell, Partition the
	// ones that own storage, in layout order.
	Cols, Required, Cells, Partition []Column
	// Finer are the Cell columns other than namespace: a tuple that narrows
	// any of them is narrower than a namespace.
	Finer                []Column
	NeedStrconv, NeedFmt bool
}

// Generate is the Go source of package shape's per-shape half: the tuple, the
// key a row is matched by, and what the hand-written algebra needs of them. It
// is gofmt-formatted. source names the spec in the header.
func Generate(s *Spec, source string) ([]byte, error) {
	d := data{Source: source, Cols: s.Columns()}
	for _, c := range d.Cols {
		if c.Required {
			d.Required = append(d.Required, c)
			d.NeedFmt = true
		} else {
			d.Cells = append(d.Cells, c)
			if c.Name != "namespace" {
				d.Finer = append(d.Finer, c)
			}
		}
		if c.Partition {
			d.Partition = append(d.Partition, c)
			if c.Type == "int64" {
				d.NeedStrconv = true
			}
		}
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, d); err != nil {
		return nil, fmt.Errorf("generate: %w", err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated code does not parse: %w\n%s", err, buf.Bytes())
	}
	return out, nil
}

