-- Convert every org_id uuid column. Partitioned parents convert their
-- partitions; partitions themselves can't be altered directly.
-- +goose StatementBegin
DO $mig$
DECLARE t record;
BEGIN
    FOR t IN
        SELECT c.relname
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND a.attname = 'org_id'
          AND a.atttypid = 'uuid'::regtype
          AND a.attnum > 0 AND NOT a.attisdropped
          AND c.relkind IN ('r', 'p') AND NOT c.relispartition
    LOOP
        EXECUTE format(
            'ALTER TABLE public.%I ALTER COLUMN org_id TYPE bigint USING public._org_new_id(org_id)',
            t.relname);
    END LOOP;
END
$mig$;
-- +goose StatementEnd

