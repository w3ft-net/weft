-- +goose Up
-- organizations.id: uuid -> bigint identity; every org reference follows.
-- One-way, maintenance-window migration (docs/plans/customer-bigint-pk.md).
-- Keeps only graybeard (id 1) and loom (id 2); every other org and its
-- data is deleted. Sequence is advanced so the next org is 3. On a DB with
-- neither org (fresh dev/test) the map is empty and this only converts types.

CREATE TABLE public._org_id_map (
    old_id uuid PRIMARY KEY,
    new_id bigint NOT NULL UNIQUE,
    name   text NOT NULL
);

INSERT INTO public._org_id_map (old_id, new_id, name)
SELECT id, CASE name WHEN 'graybeard' THEN 1 WHEN 'loom' THEN 2 END, name
FROM public.organizations
WHERE name IN ('graybeard', 'loom');

-- +goose StatementBegin
CREATE FUNCTION public._org_new_id(old uuid) RETURNS bigint
    LANGUAGE sql STABLE
    AS $$ SELECT new_id FROM public._org_id_map WHERE old_id = old $$;
-- +goose StatementEnd

-- Delete every other org (FKs cascade where they exist).
DELETE FROM public.organizations
WHERE id NOT IN (SELECT old_id FROM public._org_id_map);

-- Tables with org_id but no FK: drop rows for deleted orgs (NULL kept).
-- +goose StatementBegin
DO $mig$
DECLARE t record;
BEGIN
    FOR t IN
        SELECT c.relname
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND a.attname = 'org_id'
          AND a.atttypid = 'uuid'::regtype
          AND a.attnum > 0 AND NOT a.attisdropped
          AND c.relkind IN ('r', 'p') AND NOT c.relispartition
    LOOP
        EXECUTE format(
            'DELETE FROM public.%I WHERE org_id IS NOT NULL AND org_id NOT IN (SELECT old_id FROM
public._org_id_map)',
            t.relname);
    END LOOP;
END
$mig$;
-- +goose StatementEnd

