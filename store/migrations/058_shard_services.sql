-- +goose Up
-- shard_services records which services a shard serves, stamped at
-- christen from its bucket's services and never updated — the
-- permanent stamp that keeps a shard queryable for those services even
-- after a service later moves buckets. See docs/plans/services-3nf.md.
--
-- Many-to-many (unlike the service→bucket assignment, which is one
-- bucket per service): a shard serves many services, and a service is
-- served by many shards over time, and across customers (shards are
-- multi-tenant) — hence namespace_id, the customer-scoped key. The
-- (namespace_id, service) index is the routing lookup ("which shards
-- serve this service?"); unique(shard_id, namespace_id, service) keeps
-- a re-stamp idempotent.
CREATE TABLE shard_services (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shard_id     text   NOT NULL REFERENCES shard_records(id) ON DELETE CASCADE,
    namespace_id bigint NOT NULL REFERENCES namespaces(id)    ON DELETE CASCADE,
    service      text   NOT NULL,
    UNIQUE (shard_id, namespace_id, service)
);

CREATE INDEX idx_shard_services_ns_service ON shard_services (namespace_id, service);

