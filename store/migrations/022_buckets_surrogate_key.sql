-- +goose Up
-- Bucket surrogate keys. Text ids like "default" / "dedicated-vimgym"
-- move to a new `label` column (unique, human-readable). The primary
-- key becomes a bigint identity. This decouples "which bucket" from
-- "what it's called," so:
--   * code that needs the default bucket queries by label ("default");
--     renaming or relabeling a bucket never breaks FKs
--   * in-memory caches of bucket pointers can't silently drift — all
--     reads go to the DB; only the label→id mapping is safe to memoize
--   * shard_records.bucket_id is a tiny bigint instead of a variable-
--     length text, which the query planner prefers
--
-- This migration preserves every existing bucket/shard_records row:
-- the text id becomes the label, a fresh surrogate is generated, and
-- shard_records.bucket_id is remapped via JOIN before the text column
-- is dropped.

-- Add label, populate from current text id.
ALTER TABLE buckets ADD COLUMN label text;
UPDATE buckets SET label = id;
ALTER TABLE buckets ALTER COLUMN label SET NOT NULL;
CREATE UNIQUE INDEX buckets_label_key ON buckets(label);

-- Surrogate id. Pre-populated by the identity column default so every
-- existing row gets a number; new rows will continue to auto-assign.
ALTER TABLE buckets ADD COLUMN new_id bigint GENERATED BY DEFAULT AS IDENTITY;

-- Mirror new_id onto shard_records before we flip the FK. The JOIN is
-- on the soon-to-be-dropped text columns (buckets.id ↔
-- shard_records.bucket_id), which currently agree.
ALTER TABLE shard_records ADD COLUMN new_bucket_id bigint;
UPDATE shard_records sr
   SET new_bucket_id = b.new_id
  FROM buckets b
 WHERE sr.bucket_id = b.id;
ALTER TABLE shard_records ALTER COLUMN new_bucket_id SET NOT NULL;

-- Drop the old FK + text column, promote new_bucket_id.
ALTER TABLE shard_records DROP CONSTRAINT IF EXISTS fk_shard_records_bucket_id_buckets;
ALTER TABLE shard_records DROP CONSTRAINT IF EXISTS shard_records_bucket_id_fkey;
ALTER TABLE shard_records DROP COLUMN bucket_id;
ALTER TABLE shard_records RENAME COLUMN new_bucket_id TO bucket_id;

-- Swap buckets' primary key to the surrogate.
ALTER TABLE buckets DROP CONSTRAINT buckets_pkey;
ALTER TABLE buckets DROP COLUMN id;
ALTER TABLE buckets RENAME COLUMN new_id TO id;
ALTER TABLE buckets ADD PRIMARY KEY (id);

-- Re-add the FK against the new surrogate.
ALTER TABLE shard_records
    ADD CONSTRAINT shard_records_bucket_id_fkey
    FOREIGN KEY (bucket_id) REFERENCES buckets(id);

