-- Named credentials an org can interpolate into webhook URLs and header values
-- in /etc/notify.yaml as ${secrets.NAME}. The document then holds only the
-- reference, so it can be read, versioned and diffed without exposing a value.
CREATE TABLE public.webhook_secrets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    deleted_at timestamp with time zone,
    org_id bigint NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    name text NOT NULL,
    value text NOT NULL
);
CREATE INDEX idx_webhook_secrets_deleted_at ON public.webhook_secrets USING btree (deleted_at);
CREATE UNIQUE INDEX idx_webhook_secrets_org_name ON public.webhook_secrets USING btree (org_id, name) WHERE (deleted_at IS NULL);

